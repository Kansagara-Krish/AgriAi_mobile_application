import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../providers/app_provider.dart';
import '../constants/theme.dart';

class PdfViewerScreen extends StatelessWidget {
  final String sampleId;
  final String? reportUrl;
  final String crop;
  final String overallRisk;
  final String? agronomicSummary;

  const PdfViewerScreen({
    Key? key,
    required this.sampleId,
    this.reportUrl,
    required this.crop,
    required this.overallRisk,
    this.agronomicSummary,
  }) : super(key: key);

  @override
  Widget build(BuildContext context) {
    final provider = Provider.of<AppProvider>(context);
    final fullUrl = provider.apiService.getAbsoluteAssetUrl(reportUrl);

    return Scaffold(
      appBar: AppBar(
        title: Text('Report: $sampleId'),
        actions: [
          IconButton(
            icon: const Icon(Icons.share),
            tooltip: 'Share Report',
            onPressed: () {
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(content: Text('Report URL copied: $fullUrl')),
              );
            },
          ),
        ],
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Card(
              color: AppTheme.accentLight,
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  children: [
                    const Icon(Icons.picture_as_pdf, size: 64, color: AppTheme.alertRed),
                    const SizedBox(height: 12),
                    Text(
                      'AgriAI Diagnostic Report: $sampleId',
                      style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 18, color: AppTheme.primaryDarkGreen),
                      textAlign: TextAlign.center,
                    ),
                    const SizedBox(height: 6),
                    Text(
                      'Target Crop: $crop  •  Risk: $overallRisk',
                      style: const TextStyle(fontSize: 14, fontWeight: FontWeight.w600, color: Colors.black87),
                    ),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 16),
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text('Agronomic Diagnostic Summary', style: TextStyle(fontWeight: FontWeight.bold, fontSize: 16)),
                    const SizedBox(height: 8),
                    Text(
                      agronomicSummary ?? 'Comprehensive multimodal report generated by EfficientNetB0 CNN and XGBoost Soil models.',
                      style: const TextStyle(fontSize: 14, height: 1.4),
                    ),
                    const Divider(height: 24),
                    const Text('Official Report Endpoint:', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: Colors.black54)),
                    const SizedBox(height: 4),
                    SelectableText(
                      fullUrl.isNotEmpty ? fullUrl : 'Report available on backend database',
                      style: const TextStyle(fontSize: 12, color: Colors.blue),
                    ),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 24),
            ElevatedButton.icon(
              onPressed: () {
                ScaffoldMessenger.of(context).showSnackBar(
                  SnackBar(
                    content: Text('Opening PDF Document: $fullUrl'),
                    backgroundColor: AppTheme.primaryGreen,
                  ),
                );
              },
              icon: const Icon(Icons.file_download),
              label: const Text('Download / Open Official PDF'),
            ),
          ],
        ),
      ),
    );
  }
}
